#!/usr/bin/env node
/**
 * Generate the skills' reference files from SMBAct's own sources, or check that they are current.
 *
 *   node scripts/gen.mjs --repo <smbact-app> --cli <smbact-cli built from that repo>          # write
 *   node scripts/gen.mjs --repo <smbact-app> --cli <smbact-cli> --check                       # exit 1 on drift
 *
 * Sources (one each, nothing hand-copied):
 *   app-native/mcp/tools.manifest.json                 -> skills/smbact/references/tools.md
 *                                                         skills/smbact-desktops/references/tools.md
 *   docs/mcp.md (error table)                          -> skills/smbact/references/errors.md
 *   `smbact-cli … --help` (every subcommand)           -> skills/smbact/references/cli.md
 *   app-native/shared/actions-catalog.manifest.json    -> skills/smbact-windows/references/actions.md
 *   app-native/shared/placement/placement.manifest.json-> skills/smbact-place/references/placement-keys.md
 *                                                         skills/smbact-layouts/references/placement-keys.md
 *   docs/mcp.md "## Placing windows" (minus key table) -> skills/smbact-place/references/placing.md
 *
 * It also checks claims in the hand-written SKILL.md files: every `**Uses:**` line names only tools and CLI
 * subcommands that exist, and the router's exit-code and error-code tables match the sources.
 *
 * Only `--help` is ever run on the CLI: any other command would hand over to a running SMBAct.
 * Stdlib only. Exit 0 = clean / written, 1 = drift or a failed claim, 2 = usage.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const CHECK = args.includes("--check");
const REPO = resolve(opt("--repo") ?? process.env.SMBACT_REPO ?? "");
const CLI = opt("--cli") ?? process.env.SMBACT_CLI_BUILD;
if (!existsSync(join(REPO, "app-native/mcp/tools.manifest.json")) || !CLI || !existsSync(CLI)) {
  console.error("usage: node scripts/gen.mjs --repo <smbact-app checkout> --cli <smbact-cli built from it> [--check]");
  process.exit(2);
}

const readJson = (p) => JSON.parse(readFileSync(join(REPO, p), "utf8"));
const git = (...a) => execFileSync("git", ["-C", REPO, ...a], { encoding: "utf8" }).trim();
const SHA = git("rev-parse", "--short", "HEAD");
const VERSION = readJson("package.json").version;
const tools = readJson("app-native/mcp/tools.manifest.json");
const catalog = readJson("app-native/shared/actions-catalog.manifest.json");
const placement = readJson("app-native/shared/placement/placement.manifest.json");
const mcpDoc = readFileSync(join(REPO, "docs/mcp.md"), "utf8");
const mainRs = readFileSync(join(REPO, "cli/src/main.rs"), "utf8");
const placeRs = readFileSync(join(REPO, "cli/src/place.rs"), "utf8");

const header = (what) =>
  `<!-- Generated by scripts/gen.mjs from smbact-app ${SHA} (SMBAct ${VERSION}): ${what}. Do not edit; regenerate. -->\n\n`;
const cell = (v) => (v === null || v === undefined || v === "" ? "—" : String(v).replace(/\|/g, "\\|").replace(/\n/g, " "));
const code = (v) => (v === null || v === undefined ? "—" : `\`${String(v).replace(/\|/g, "\\|")}\``);

// ------------------------------------------------------------------ tools.md
function schemaType(p) {
  if (p.enum) return p.enum.map((e) => `\`${e}\``).join(" \\| ");
  if (p.oneOf || p.anyOf) return (p.oneOf ?? p.anyOf).map(schemaType).join(" or ");
  let t = Array.isArray(p.type) ? p.type.join("/") : (p.type ?? "any");
  if (t === "array" && p.items) t = `array of ${p.items.type ?? "object"}${p.items.enum ? ` (${p.items.enum.join(", ")})` : ""}`;
  const lim = [];
  if (p.minimum !== undefined) lim.push(`≥ ${p.minimum}`);
  if (p.maximum !== undefined) lim.push(`≤ ${p.maximum}`);
  if (p.minLength !== undefined) lim.push(`len ≥ ${p.minLength}`);
  if (p.maxLength !== undefined) lim.push(`len ≤ ${p.maxLength}`);
  if (p.minItems !== undefined) lim.push(`items ≥ ${p.minItems}`);
  if (p.maxItems !== undefined) lim.push(`items ≤ ${p.maxItems}`);
  return lim.length ? `${t} (${lim.join(", ")})` : t;
}

function toolsMd() {
  let s = header("app-native/mcp/tools.manifest.json") + "# SMBAct MCP tools\n\n";
  s += `${tools.tools.length} tools. **app_only**: served only by the running app (and by \`smbact-cli mcp serve\` while it proxies to the app), not by a standalone \`smbact-cli mcp serve\`. **Switch**: the key in \`mcp.json\` → \`settings.tools\` (\`smbact-cli mcp config tool.<name>=on|off\`); no switch = always listed. Only \`get_capabilities\` and \`get_version\` work without a license.\n\n`;
  s += "| Tool | Title | read-only | destructive | idempotent | app_only | switch | license-free |\n|---|---|---|---|---|---|---|---|\n";
  for (const t of tools.tools) {
    const a = t.annotations ?? {};
    s += `| \`${t.name}\` | ${cell(t.title)} | ${a.readOnlyHint ? "yes" : "no"} | ${a.destructiveHint ? "**yes**" : "no"} | ${a.idempotentHint ? "yes" : "no"} | ${t.app_only ? "**yes**" : "no"} | ${code(t.setting)} | ${t.license_free ? "yes" : "no"} |\n`;
  }
  s += `\nWindow fields (\`list_windows\` \`fields\`): ${tools.window_fields.map((f) => `\`${f}\``).join(", ")}. Default: ${tools.default_window_fields.map((f) => `\`${f}\``).join(", ")}. Only when known: ${tools.when_known_window_fields.map((f) => `\`${f}\``).join(", ")}.\n`;
  for (const t of tools.tools) {
    s += `\n## ${t.name}\n\n${t.description}\n\n`;
    const props = t.inputSchema?.properties ?? {};
    const req = new Set(t.inputSchema?.required ?? []);
    if (!Object.keys(props).length) {
      s += "No arguments.\n";
      continue;
    }
    s += "| Argument | Type | Required | Default | Description |\n|---|---|---|---|---|\n";
    for (const [k, p] of Object.entries(props)) {
      s += `| \`${k}\` | ${cell(schemaType(p))} | ${req.has(k) ? "yes" : "no"} | ${code(p.default)} | ${cell(p.description)} |\n`;
    }
  }
  return s;
}

// ------------------------------------------------------------------ errors.md
function errorTable() {
  const start = mcpDoc.indexOf("| Code | Meaning |");
  if (start < 0) throw new Error("docs/mcp.md: error table not found");
  const lines = mcpDoc.slice(start).split("\n");
  const out = [];
  for (const l of lines) {
    if (!l.startsWith("|")) break;
    out.push(l);
  }
  return out;
}
const errorCodes = () =>
  errorTable()
    .slice(2)
    .flatMap((l) => [...l.split("|")[1].matchAll(/`([a-z_]+)`/g)].map((m) => m[1]));

function errorsMd() {
  return (
    header("the error table in docs/mcp.md") +
    "# SMBAct MCP error codes\n\nA failed tool call is a tool result with `isError: true` and the text `{\"error\": \"<code>\", \"message\": \"…\"}`. Read `message`: it names the argument, the display or the window.\n\n" +
    errorTable().join("\n") +
    "\n"
  );
}

// ------------------------------------------------------------------ cli.md
const help = (...a) => execFileSync(CLI, [...a, "--help"], { encoding: "utf8", env: { ...process.env, NO_COLOR: "1" } });
function subcommands(text) {
  const m = text.split("\nCommands:\n")[1];
  if (!m) return [];
  return m
    .split("\n\n")[0]
    .split("\n")
    .map((l) => l.trim().split(/\s+/)[0])
    .filter((c) => c && c !== "help");
}
function cliTree() {
  const tree = [];
  const walk = (path) => {
    const text = help(...path);
    tree.push({ path, text });
    for (const c of subcommands(text)) walk([...path, c]);
  };
  walk([]);
  return tree;
}
function cliMd(tree) {
  const version = execFileSync(CLI, ["--version"], { encoding: "utf8" }).trim();
  let s = header("`smbact-cli --help` of every subcommand") + `# smbact-cli reference\n\n\`${version}\`, built from smbact-app ${SHA}. The help text below is verbatim.\n`;
  for (const { path, text } of tree) s += `\n## smbact-cli ${path.join(" ")}\n\n\`\`\`text\n${text.trimEnd().replaceAll(process.env.HOME, "~")}\n\`\`\`\n`;
  return s;
}

// ------------------------------------------------------------------ actions.md
function actionsMd() {
  const a = catalog.actions;
  let s = header("app-native/shared/actions-catalog.manifest.json") + "# SMBAct window actions\n\n";
  s += `${a.length} actions. **MCP**: the tool that runs it (\`window_action\` takes the id as \`action\`; the \`hide-*\` ones are \`minimize_all\` with a \`display\`). **CLI**: \`run\` = \`smbact-cli run <id>\`, \`special\` = also through \`run\`, \`minimize-all\` = that subcommand, — = not in the CLI. **Cycle**: repeated presses of the hotkey or \`smbact-cli run <id>\` without \`--window-id\` on the same window within 2 s step through this chain; MCP \`window_action\` never cycles.\n\n`;
  s += "| Action | Category | What | Platforms | MCP | CLI | Cycle |\n|---|---|---|---|---|---|---|\n";
  for (const x of a) {
    const mcp = x.mcp ? `${x.mcp.tool}${x.mcp.display ? ` (${x.mcp.display})` : ""}` : "—";
    s += `| \`${x.id}\`${x.legacy ? " (legacy)" : ""} | ${x.category} | ${cell(x.hint)} | ${x.platforms.length === catalog.platforms.length ? "all" : x.platforms.join(", ")} | ${cell(mcp)} | ${cell(x.cli)} | ${x.cycle?.length ? x.cycle.join(" → ") : "—"} |\n`;
  }
  return s;
}

// ------------------------------------------------------------------ placement-keys.md / placing.md
function placementKeysMd() {
  let s = header("app-native/shared/placement/placement.manifest.json") + "# place_windows keys\n\n";
  s += `Model version ${placement.model_version}, phase ${placement.phase} built, at most ${placement.max_placements} placements per request. **Level**: \`request\` keys sit next to \`placements\`, \`placement\` keys inside each placement. **Entries**: where the key is accepted (\`mcp\` = \`place_windows\`, \`cli\` = \`smbact-cli place\`, \`url\` = phase 2, not built). **Phase** > ${placement.phase} = not available yet: do not send it.\n\n`;
  s += "| Key | Level | Kind / values | Limits | Default | Entries | Phase | CLI flag | Description |\n|---|---|---|---|---|---|---|---|---|\n";
  for (const k of placement.keys) {
    const values = k.values ? k.values.map((v) => `\`${v}\``).join(", ") + (k.later_values ? ` (later: ${k.later_values.join(", ")})` : "") : k.kind + (k.role ? ` (${k.role})` : "");
    const lim = [k.min !== null ? `≥ ${k.min}` : "", k.max !== null ? `≤ ${k.max}` : "", k.min_length !== null ? `len ≥ ${k.min_length}` : "", k.max_length !== null ? `len ≤ ${k.max_length}` : ""].filter(Boolean).join(", ");
    s += `| \`${k.key}\` | ${k.level} | ${cell(values)} | ${cell(lim)} | ${code(k.default)} | ${k.entries.join(", ")} | ${k.phase} | ${code(k.cli_flag)} | ${cell(k.description)} |\n`;
  }
  return s;
}
function placingMd() {
  const start = mcpDoc.indexOf("## Placing windows");
  const end = mcpDoc.indexOf("\n## ", start + 5);
  let sec = mcpDoc.slice(start, end < 0 ? undefined : end);
  const before = sec;
  sec = sec.replace(/<!-- placement-keys:begin[^>]*-->[\s\S]*?<!-- placement-keys:end -->/, "The key table is in `placement-keys.md`.");
  if (sec === before) throw new Error("docs/mcp.md: placement-keys markers not found");
  return header('the "Placing windows" section of docs/mcp.md') + sec.replace(/^## /, "# ").trimEnd() + "\n";
}

// ------------------------------------------------------------------ claims in SKILL.md
function claims(tree) {
  const problems = [];
  const toolNames = new Set(tools.tools.map((t) => t.name));
  const cliCmds = new Set(tree.filter((n) => n.path.length).map((n) => n.path.join(" ")));
  for (const dir of readdirSync(join(ROOT, "skills"))) {
    const f = join(ROOT, "skills", dir, "SKILL.md");
    if (!existsSync(f)) {
      problems.push(`skills/${dir}: no SKILL.md`);
      continue;
    }
    const text = readFileSync(f, "utf8");
    const fm = text.match(/^---\nname: ([a-z0-9-]+)\ndescription: (.+)\n---\n/);
    if (!fm) problems.push(`skills/${dir}/SKILL.md: frontmatter must be exactly name + description`);
    else {
      if (fm[1] !== dir) problems.push(`skills/${dir}/SKILL.md: name "${fm[1]}" != folder`);
      if (fm[2].length > 1024) problems.push(`skills/${dir}/SKILL.md: description ${fm[2].length} > 1024 chars`);
    }
    if (text.split("\n").length > 500) problems.push(`skills/${dir}/SKILL.md: over 500 lines`);
    const uses = text.match(/^\*\*Uses:\*\* (.+)$/m);
    if (!uses) problems.push(`skills/${dir}/SKILL.md: no **Uses:** line`);
    else
      for (const m of uses[1].matchAll(/`([^`]+)`/g)) {
        const u = m[1];
        if (u.startsWith("smbact-cli ")) {
          const c = u.slice(11).split(" --")[0].trim();
          if (!cliCmds.has(c)) problems.push(`skills/${dir}: Uses names \`${u}\`, not a smbact-cli subcommand`);
        } else if (!toolNames.has(u)) problems.push(`skills/${dir}: Uses names \`${u}\`, not an MCP tool`);
      }
    for (const m of text.matchAll(/references\/([a-z-]+\.md)/g))
      if (!existsSync(join(ROOT, "skills", dir, "references", m[1]))) problems.push(`skills/${dir}: links references/${m[1]}, missing`);
  }
  // router: exit codes and error codes
  const router = readFileSync(join(ROOT, "skills/smbact/SKILL.md"), "utf8");
  const exitSrc = new Set([...mainRs.matchAll(/const EXIT_[A-Z_]+: u8 = (\d+);/g)].map((m) => m[1]).concat(["0", "1", "2"]));
  const placeExit = placeRs.match(/Exit codes: ([^\n\\]+)/);
  if (!placeExit) problems.push("cli/src/place.rs: no 'Exit codes:' line in the place help");
  else for (const m of placeExit[1].matchAll(/\b(\d+)\b/g)) exitSrc.add(m[1]);
  const exitTable = router.split("<!-- exit-codes -->")[1]?.split("<!-- /exit-codes -->")[0] ?? "";
  const exitDoc = new Set([...exitTable.matchAll(/^\| `?(\d+)`? \|/gm)].map((m) => m[1]));
  if (!exitDoc.size) problems.push("skills/smbact: no <!-- exit-codes --> table");
  for (const c of exitSrc) if (!exitDoc.has(c)) problems.push(`skills/smbact: exit code ${c} is in the CLI source but not in the table`);
  for (const c of exitDoc) if (!exitSrc.has(c)) problems.push(`skills/smbact: exit code ${c} is in the table but not in the CLI source`);
  const errSrc = new Set(errorCodes());
  const errTable = router.split("<!-- error-codes -->")[1]?.split("<!-- /error-codes -->")[0] ?? "";
  for (const line of errTable.split("\n").filter((l) => l.startsWith("| `")))
    for (const m of line.split("|")[1].matchAll(/`([a-z_]+)`/g))
      if (!errSrc.has(m[1])) problems.push(`skills/smbact: error code \`${m[1]}\` is not in docs/mcp.md`);
  return problems;
}

// ------------------------------------------------------------------ run
const tree = cliTree();
const files = {
  "skills/smbact/references/tools.md": toolsMd(),
  "skills/smbact-desktops/references/tools.md": toolsMd(),
  "skills/smbact/references/errors.md": errorsMd(),
  "skills/smbact/references/cli.md": cliMd(tree),
  "skills/smbact-windows/references/actions.md": actionsMd(),
  "skills/smbact-place/references/placement-keys.md": placementKeysMd(),
  "skills/smbact-place/references/placing.md": placingMd(),
  "skills/smbact-layouts/references/placement-keys.md": placementKeysMd(),
  "VERIFIED.json":
    JSON.stringify(
      { smbact_app: SHA, smbact_version: VERSION, tools: tools.tools.length, actions: catalog.actions.length, placement_keys: placement.keys.length, placement_phase: placement.phase },
      null,
      2,
    ) + "\n",
};
let drift = 0;
for (const [rel, content] of Object.entries(files)) {
  const path = join(ROOT, rel);
  const old = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (CHECK) {
    if (old !== content) {
      console.log(`stale: ${rel}`);
      drift++;
    }
  } else if (old !== content) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote: ${rel}`);
  }
}
const problems = claims(tree);
for (const p of problems) console.log(`claim: ${p}`);
const bad = drift + problems.length;
console.log(bad ? `FAIL: ${drift} stale file(s), ${problems.length} claim problem(s)` : `ok: references current with smbact-app ${SHA}; claims hold`);
process.exit(bad ? 1 : 0);
